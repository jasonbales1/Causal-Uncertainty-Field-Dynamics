def evaluate_borexino_full_solar_msw_spectrum(elem_res: dict) -> dict:
    """
    Update 3: Full 5-Branch Borexino & SNO Solar Neutrino MSW Survival Spectrum
    (pp, 7Be, pep, CNO, 8B), CNO Solar Core Neutrino Flux (Borexino 2020, Nature 587, 577),
    and Earth Nighttime Matter Regeneration A_DN (SNO 2013, PRC 88, 025501).
    """
    delta_b = float(DELTA_BARYON_PHASE)
    n_c = float(BARYON_VALENCE_QUARKS)
    delta_d = float(delta_b / n_c)

    f61 = elem_res["solar_msw_cpv_fcnc_desi_suite"]
    v_cc_core_ev = float(f61["v_cc_solar_core_ev"])
    dm21_sq_ev2 = float(elem_res["neutrinos"]["dm21_sq_pred_ev2"])
    mixing = elem_res["mixing"]
    s12_sq = float(mixing["sin2_12_pmns"])
    c12_sq = float(1.0 - s12_sq)
    s13_sq = float(mixing["sin2_13_pmns"])
    c13_sq = float(1.0 - s13_sq)
    cos_2th12 = float(c12_sq - s12_sq)
    sin2_2th12 = float(4.0 * s12_sq * c12_sq)

    m_e_mev = float(elem_res["leptons"][0]["pred_mev"])

    def _p_ee_msw(e_nu_mev: float, r_shell_weight: float = 1.0) -> float:
        eps_m = (2.0 * (r_shell_weight * v_cc_core_ev) * c13_sq * (e_nu_mev * 1.0e6)) / dm21_sq_ev2
        cos_2th12_m = (cos_2th12 - eps_m) / np.sqrt(((cos_2th12 - eps_m) ** 2) + sin2_2th12)
        return float((c13_sq ** 2) * (0.5 + 0.5 * cos_2th12_m * cos_2th12) + (s13_sq ** 2))

    # 64-node Gauss-Legendre integration across continuous beta spectra (pp, CNO, 8B):
    xi_gl, wi_gl = roots_legendre(64)

    # 1. pp branch (Q_pp = 0.420 MeV):
    q_pp = 0.420
    e_pp = 0.5 * q_pp * (xi_gl + 1.0)
    w_pp_gl = 0.5 * q_pp * wi_gl
    e_el_pp = (q_pp + m_e_mev) - e_pp
    p_el_pp = np.sqrt(np.maximum(0.0, (e_el_pp ** 2) - (m_e_mev ** 2)))
    spec_pp = (e_pp ** 2) * e_el_pp * p_el_pp
    p_ee_pp_pred = float(np.sum(w_pp_gl * spec_pp * np.array([_p_ee_msw(float(ev)) for ev in e_pp])) / np.sum(w_pp_gl * spec_pp))
    p_ee_pp_obs = 0.5700
    p_ee_pp_sigma = 0.0900

    # 2. 7Be monoenergetic electron-capture line (E_nu = 0.862 MeV):
    p_ee_be7_pred = _p_ee_msw(0.862, r_shell_weight=0.92)
    p_ee_be7_obs = 0.5300
    p_ee_be7_sigma = 0.0500

    # 3. pep monoenergetic line (E_nu = 1.442 MeV, produced across outer pp shell r_shell_weight = 0.85):
    p_ee_pep_pred = _p_ee_msw(1.442, r_shell_weight=0.85)
    p_ee_pep_obs = 0.4300
    p_ee_pep_sigma = 0.1100

    # 4. CNO cycle (13N Q = 1.199 MeV + 15O Q = 1.732 MeV beta spectrum & Borexino 2020 CNO flux):
    q_15o = 1.732
    e_cno = 0.5 * q_15o * (xi_gl + 1.0)
    w_cno_gl = 0.5 * q_15o * wi_gl
    e_el_cno = (q_15o + m_e_mev) - e_cno
    p_el_cno = np.sqrt(np.maximum(0.0, (e_el_cno ** 2) - (m_e_mev ** 2)))
